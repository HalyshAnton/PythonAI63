# користувач вводить назву товару, вивести про цей товар інформацію


product = input("Введіть назву товару: ")

print("Вітаємо в нащому магазині")

# змінна чи зроблена покупка
is_purchased = False

# перевірямо варіанти відомих нам товарів
if product == "пиріжок":
    is_purchased = True
    print("Є з вишнею або з шоколадом")

elif product == "морозиво":
    is_purchased = True
    print("Залишився лише пломбір")

elif product == "ковбаса":
    is_purchased = True
    print("Вам сироркопчену чи варену")

else: # невідомий нам продукт
    print("У нас такого немає")


# чи відбулася покупка
if is_purchased:
    print("Дякуємо за покупку")
else:
    print(f"Можливо ви знайдете {product} в іншому магазині")

